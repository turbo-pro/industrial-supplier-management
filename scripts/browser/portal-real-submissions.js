async page => {
  const admin = await page.context().newPage(), reader = await page.context().newPage();
  try {
    await page.getByRole('textbox', { name: '密码', exact: true }).fill('Portal#Pass123');
    const login = page.waitForResponse(r => r.url().endsWith('/portal/auth/login') && r.status() === 200);
    await page.getByRole('button', { name: '登录门户', exact: true }).click();
    const session = (await (await login).json()).data;
    await page.getByRole('button', { name: '填写证照申请', exact: true }).click();
    await page.getByRole('combobox', { name: '申请资质类型', exact: true }).selectOption('21080');
    await page.locator('body').ariaSnapshot();
    const bytes = Buffer.alloc(1024 * 1024 + 128, 65); bytes.write('%PDF-1.7\nSYNTHETIC-PORTAL-EVIDENCE\n');
    let firstChunkRequests = 0;
    await page.route('**/api/portal/certificate-uploads/*/chunks/0', async route => { firstChunkRequests++; await route.continue(); });
    await page.route('**/api/portal/certificate-uploads/*/chunks/1', route => route.abort('failed'), { times: 1 });
    await page.getByLabel('选择证照原件', { exact: true }).setInputFiles({ name: 'portal-rejected.pdf', mimeType: 'application/pdf', buffer: bytes });
    await page.getByRole('button', { name: '上传证照原件', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '同页点击继续上传' }).waitFor();
    await page.getByRole('button', { name: '继续上传原件', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '原件上传完成' }).waitFor();
    if (firstChunkRequests !== 1) throw new Error('Resume resent the already recorded first chunk');
    await page.getByRole('textbox', { name: '申请证书编号', exact: true }).fill('PORTAL-REJECTED');
    await page.getByLabel('申请到期日期', { exact: true }).fill('2030-12-31');
    await page.getByRole('checkbox', { name: '确认原件与填写内容一致，提交后等待员工核验', exact: true }).check();
    let submittedId;
    await page.route('**/api/portal/certificate-submissions', async route => {
      if (route.request().method() !== 'POST') return route.continue();
      const response = await route.fetch();
      if (response.status() !== 200) throw new Error('Real submission did not commit before response loss');
      submittedId = (await response.json()).data.id; await route.abort('failed');
    }, { times: 1 });
    await page.getByRole('button', { name: '确认提交证照申请', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '结果未知' }).waitFor();
    if (await page.getByRole('textbox', { name: '申请证书编号', exact: true }).isEnabled()) throw new Error('Unknown submission allowed payload mutation');
    await page.getByRole('button', { name: '重试同一证照申请', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '证照申请已提交：PORTAL-REJECTED' }).waitFor();
    await page.getByText('第 1 页，共 1 条申请', { exact: true }).waitFor();
    const employeeLogin = async (tab, username) => {
      await tab.goto('__ADMIN_URL__/suppliers/qualifications');
      await tab.getByRole('textbox', { name: '租户编码', exact: true }).fill('PORTAL-BROWSER');
      await tab.getByRole('textbox', { name: '用户名', exact: true }).fill(username);
      await tab.getByRole('textbox', { name: '密码', exact: true }).fill('Employee#Pass123');
      await tab.getByRole('button', { name: '登录系统', exact: true }).click();
      await tab.getByRole('button', { name: '登录系统', exact: true }).waitFor({ state: 'hidden' });
      await tab.goto('__ADMIN_URL__/suppliers/qualifications');
      await tab.getByRole('heading', { name: '资质证照', exact: true }).waitFor();
    };
    await employeeLogin(reader, 'browser-reader');
    const readerToken = await reader.evaluate(() => sessionStorage.getItem('ism.admin.accessToken'));
    const denied = await reader.request.post(`__ADMIN_URL__/api/qualifications/${submittedId}/verify`, { headers: { Authorization: `Bearer ${readerToken}` }, data: { decision: 'APPROVE', comment: '只读越权', version: 0 } });
    if (denied.status() !== 403) throw new Error('Readonly employee verified portal certificate');
    await employeeLogin(admin, 'browser-admin');
    const review = async (no, approve) => {
      const row = admin.getByRole('row').filter({ hasText: no }).first(); await row.waitFor();
      const direct = row.getByRole('button', { name: approve ? '通过' : '拒绝', exact: true });
      if (await direct.count()) await direct.click();
      else { await row.getByRole('button', { name: `${no}的更多操作`, exact: true }).click(); await admin.getByRole('menuitem', { name: approve ? '核验通过' : '核验拒绝', exact: true }).click(); }
      const dialog = admin.getByRole('dialog', { name: '资质核验', exact: true });
      await dialog.getByRole('textbox').fill(approve ? 'PRIVATE_REVIEW_APPROVAL' : 'PRIVATE_REVIEW_REJECTION');
      const finished = admin.waitForResponse(r => r.url().includes('/qualifications/') && r.url().endsWith('/verify') && r.request().method() === 'POST');
      await dialog.getByRole('button', { name: '确定', exact: true }).click();
      if ((await finished).status() !== 200) throw new Error('Employee verification failed');
    };
    await review('PORTAL-REJECTED', false);
    await page.getByRole('button', { name: '刷新证照申请', exact: true }).click();
    await page.locator('article.request').filter({ hasText: 'PORTAL-REJECTED' }).getByRole('heading').filter({ hasText: '核验拒绝' }).waitFor();
    await page.getByRole('textbox', { name: '申请证书编号', exact: true }).fill('PORTAL-APPROVED');
    await page.getByLabel('选择证照原件', { exact: true }).setInputFiles({ name: 'portal-approved.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nAPPROVED-PORTAL-ORIGINAL') });
    await page.getByRole('button', { name: '上传证照原件', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '原件上传完成' }).waitFor();
    await page.getByRole('checkbox', { name: '确认原件与填写内容一致，提交后等待员工核验', exact: true }).check();
    await page.getByRole('button', { name: '确认提交证照申请', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '证照申请已提交：PORTAL-APPROVED' }).waitFor();
    await admin.reload(); await review('PORTAL-APPROVED', true);
    await page.getByRole('button', { name: '刷新证照申请', exact: true }).click();
    await page.locator('article.request').filter({ hasText: 'PORTAL-APPROVED' }).getByRole('heading').filter({ hasText: '核验通过' }).waitFor();
    await page.getByRole('button', { name: '查看本企业证照', exact: true }).click();
    await page.getByRole('button', { name: '查看证照 PORTAL-APPROVED', exact: true }).click();
    await page.getByRole('heading', { name: '证照详情', exact: true }).waitFor();
    if (await page.getByText('PRIVATE_', { exact: false }).count()) throw new Error('Internal reviewer comment leaked');
    const records = await page.request.get(new URL('/api/portal/certificate-submissions', page.url()).href, { headers: { Authorization: `Bearer ${session.accessToken}` } });
    const all = (await records.json()).data;
    if (all.total !== 2 || all.items.filter(r => r.status === 'VALID').length !== 1) throw new Error('Portal submission count/outcome mismatch');
    const approved = all.items.find(r => r.status === 'VALID');
    const original = await page.request.get(new URL(`/api/portal/qualifications/${approved.id}/content`, page.url()).href, { headers: { Authorization: `Bearer ${session.accessToken}` } });
    if ((await original.body()).toString() !== '%PDF-1.7\nAPPROVED-PORTAL-ORIGINAL' || !original.headers()['content-disposition'].includes('portal-approved.pdf')) throw new Error('Approved original or filename mismatch');
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByRole('heading', { name: '本企业证照申请记录', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'output/playwright/portal-real-submissions-desktop.png' });
    await page.setViewportSize({ width: 375, height: 812 });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Portal submission mobile overflow');
    if (await page.locator('.submissions label.check').first().evaluate(el => getComputedStyle(el).flexDirection) !== 'row') throw new Error('Checkbox inherited a vertical label layout');
    await page.getByRole('heading', { name: '本企业证照申请记录', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'output/playwright/portal-real-submissions-mobile.png' });
    await page.getByRole('button', { name: '退出当前会话' }).click();
    await page.getByRole('status').filter({ hasText: '已退出当前会话' }).waitFor();
    const stale = await page.request.get(new URL('/api/portal/certificate-submissions', page.url()).href, { headers: { Authorization: `Bearer ${session.accessToken}` } });
    if (stale.status() !== 401) throw new Error('Logged out portal still read submissions');
  } finally { await admin.close(); await reader.close(); }
}
