async page => {
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('Portal#Pass123');
  const login = page.waitForResponse(r => r.url().endsWith('/portal/auth/login') && r.status() === 200);
  await page.getByRole('button', { name: '登录门户' }).click();
  const session = (await (await login).json()).data;
  await page.getByRole('heading', { name: '本企业档案' }).waitFor();
  await page.route('**/api/portal/qualifications?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ success: false }) }), { times: 1 });
  await page.getByRole('button', { name: '查看本企业证照' }).click();
  await page.getByRole('alert').filter({ hasText: '证照服务暂不可用' }).waitFor();
  await page.getByRole('button', { name: '刷新证照列表' }).click();
  await page.getByText('第 1 页，共 12 条', { exact: true }).waitFor();
  await page.locator('body').ariaSnapshot();
  await page.getByRole('button', { name: '下一页证照', exact: true }).click();
  await page.getByText('第 2 页，共 12 条', { exact: true }).waitFor();
  if (await page.getByRole('button', { name: '下一页证照', exact: true }).isEnabled()) throw new Error('Last page not bounded');
  await page.getByRole('combobox', { name: '证照状态', exact: true }).selectOption('EXPIRED');
  await page.getByRole('button', { name: '筛选证照', exact: true }).click();
  await page.getByText('第 1 页，共 6 条', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: '证照关键词', exact: true }).fill('missing-certificate');
  await page.getByRole('button', { name: '筛选证照', exact: true }).click();
  await page.getByText('暂无符合条件的已发布证照。', { exact: false }).waitFor();
  await page.getByRole('textbox', { name: '证照关键词', exact: true }).fill('CERT-BROWSER-11');
  await page.getByRole('button', { name: '筛选证照', exact: true }).click();
  await page.getByText('第 1 页，共 1 条', { exact: true }).waitFor();
  await page.route('**/api/portal/qualifications/21111', route => route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ success: false }) }), { times: 1 });
  await page.getByRole('button', { name: '查看证照 CERT-BROWSER-11', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '证照或原件当前不可用' }).waitFor();
  await page.getByRole('button', { name: '查看证照 CERT-BROWSER-11', exact: true }).click();
  await page.getByRole('heading', { name: '证照详情', exact: true }).waitFor();
  if (!await page.locator('[aria-labelledby="certificate-detail-title"]').evaluate(el => el === document.activeElement)) throw new Error('Detail did not receive keyboard focus');
  await page.getByText('已过期 2 天', { exact: true }).waitFor();
  if (await page.getByText('PRIVATE_', { exact: false }).count()) throw new Error('Private certificate fields leaked');
  const path = id => new URL(`/api/portal/qualifications/${id}/content`, page.url()).href;
  const headers = { Authorization: `Bearer ${session.accessToken}` };
  const foreign = await page.request.get(path('21120'), { headers });
  if (foreign.status() !== 404) throw new Error('Other enterprise certificate leaked');
  const original = await page.request.get(path('21111'), { headers });
  if (original.status() !== 200 || (await original.body()).toString() !== 'BROWSER-CERTIFICATE-11'
      || original.headers()['cache-control'] !== 'no-store' || original.headers()['x-content-type-options'] !== 'nosniff'
      || !original.headers()['content-disposition'].startsWith('attachment;')) throw new Error('Original file binding or safe headers failed');
  await page.route('**/api/portal/qualifications/21111/content', route => route.abort('failed'), { times: 1 });
  await page.getByRole('button', { name: '下载证照原件', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '下载失败' }).waitFor();
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载证照原件', exact: true }).click();
  const download = await pendingDownload;
  if (download.suggestedFilename() !== '证照原件-11.pdf' || await download.failure()) throw new Error('Browser download failed');
  await page.getByRole('status').filter({ hasText: '原件已交给浏览器下载' }).waitFor();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('heading', { name: '证照详情', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/playwright/portal-real-certificates-desktop.png' });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('heading', { name: '证照详情', exact: true }).scrollIntoViewIfNeeded();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Certificate mobile overflow');
  await page.screenshot({ path: 'output/playwright/portal-real-certificates-mobile.png' });
  await page.getByRole('button', { name: '退出当前会话' }).click();
  await page.getByRole('status').filter({ hasText: '已退出当前会话' }).waitFor();
  const replay = await page.request.get(path('21111'), { headers });
  if (replay.status() !== 401 || await page.getByRole('heading', { name: '本企业资质证照', exact: true }).count()) throw new Error('Certificate access survived logout');
}
