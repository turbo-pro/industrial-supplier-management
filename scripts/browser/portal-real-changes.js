async page => {
  const admin = await page.context().newPage();
  const reader = await page.context().newPage();
  try {
    await page.getByRole('textbox', { name: '租户编码', exact: true }).fill('PORTAL-BROWSER');
    await page.getByRole('textbox', { name: '用户名', exact: true }).fill('browser.user');
    await page.getByRole('textbox', { name: '密码', exact: true }).fill('Portal#Pass123');
    await page.getByRole('button', { name: '登录门户', exact: true }).click();
    await page.getByRole('heading', { name: '企业资料变更申请', exact: true }).waitFor();
    const submit = async (reason, address) => {
      await page.getByRole('button', { name: '申请资料变更', exact: true }).click();
      await page.locator('body').ariaSnapshot();
      await page.getByRole('textbox', { name: '变更企业地址', exact: true }).fill(address);
      await page.getByRole('textbox', { name: '资料变更原因', exact: true }).fill(reason);
      await page.getByRole('button', { name: '确认提交申请', exact: true }).click();
      await page.getByRole('status').filter({ hasText: '申请已提交' }).waitFor();
      const row = page.locator('article.change-item').filter({ hasText: reason });
      await row.getByRole('heading').filter({ hasText: '待审核' }).waitFor();
      await page.locator('.profile-section > dl').getByText('示例工业园区一号', { exact: true }).waitFor();
      return row;
    };
    const cancelled = await submit('浏览器撤回验证', '撤回前的地址');
    await cancelled.getByRole('button', { name: '撤回申请', exact: true }).click();
    await cancelled.getByRole('button', { name: '确认撤回申请', exact: true }).click();
    await cancelled.getByRole('heading').filter({ hasText: '已撤回' }).waitFor();
    await submit('浏览器驳回验证', '不应生效的地址');
    const employeeLogin = async (tab, username) => {
      await tab.goto('__ADMIN_URL__/suppliers/master?supplierId=21005');
      await tab.locator('body').ariaSnapshot();
      await tab.getByRole('textbox', { name: '租户编码', exact: true }).fill('PORTAL-BROWSER');
      await tab.getByRole('textbox', { name: '用户名', exact: true }).fill(username);
      await tab.getByRole('textbox', { name: '密码', exact: true }).fill('Employee#Pass123');
      await tab.getByRole('button', { name: '登录系统', exact: true }).click();
      await tab.getByRole('button', { name: '登录系统', exact: true }).waitFor({ state: 'hidden' });
      await tab.goto('__ADMIN_URL__/suppliers/master?supplierId=21005');
      const panel = tab.getByRole('region', { name: '门户企业资料变更审核', exact: true });
      await panel.waitFor(); await panel.getByRole('button', { name: '资料变更审核', exact: true }).click();
      return panel;
    };
    const readonly = await employeeLogin(reader, 'browser-reader');
    await readonly.getByText('当前账号只读，无资料变更审核权限。', { exact: true }).waitFor();
    await readonly.getByRole('row').filter({ hasText: '浏览器驳回验证' }).getByRole('button', { name: '查看变更' }).click();
    if (await readonly.getByRole('button', { name: '批准并更新档案' }).count()) throw new Error('Read-only reviewer action visible');
    const readerToken = await reader.evaluate(() => sessionStorage.getItem('ism.admin.accessToken'));
    const requests = await reader.request.get('__ADMIN_URL__/api/suppliers/21005/profile-changes', { headers: { Authorization: `Bearer ${readerToken}` } });
    const pending = (await requests.json()).data.items.find(item => item.status === 'SUBMITTED');
    const denied = await reader.request.post(`__ADMIN_URL__/api/suppliers/21005/profile-changes/${pending.id}/review`, { headers: { Authorization: `Bearer ${readerToken}` }, data: { version: pending.version, decision: 'APPROVE', comment: '只读越权验证' } });
    if (denied.status() !== 403) throw new Error('Read-only employee could review');
    let panel = await employeeLogin(admin, 'browser-admin');
    await admin.route('**/api/suppliers/21005/profile-changes?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'TEST_UNAVAILABLE', message: '验收注入：申请列表暂不可用' } }) }), { times: 1 });
    await panel.getByRole('button', { name: '刷新资料变更', exact: true }).click();
    await panel.getByRole('alert').filter({ hasText: '申请列表暂不可用' }).waitFor();
    await panel.getByRole('button', { name: '刷新资料变更', exact: true }).click();
    await panel.getByRole('row').filter({ hasText: '浏览器驳回验证' }).waitFor();
    const review = async (reason, approve) => {
      await panel.getByRole('row').filter({ hasText: reason }).getByRole('button', { name: '查看变更' }).click();
      await panel.getByRole('textbox', { name: '资料变更审核说明', exact: true }).fill(approve ? '独立复核企业地址后批准' : '材料需更正，请重新申请');
      await panel.getByRole('button', { name: approve ? '批准并更新档案' : '驳回变更申请', exact: true }).click();
      await admin.getByRole('button', { name: '确定', exact: true }).click();
    };
    await review('浏览器驳回验证', false);
    await panel.getByRole('status').filter({ hasText: '已驳回' }).waitFor();
    await page.getByRole('button', { name: '刷新申请记录', exact: true }).click();
    await page.locator('article.change-item').filter({ hasText: '浏览器驳回验证' }).getByRole('heading').filter({ hasText: '已驳回' }).waitFor();
    await submit('浏览器批准验证', '批准后的工业园地址');
    await panel.getByRole('button', { name: '刷新资料变更', exact: true }).click();
    await review('浏览器批准验证', true);
    await admin.getByText('批准后的工业园地址', { exact: true }).first().waitFor();
    await page.getByRole('button', { name: '刷新企业档案', exact: true }).click();
    await page.locator('.profile-section > dl').getByText('批准后的工业园地址', { exact: true }).waitFor();
    await page.locator('article.change-item').filter({ hasText: '浏览器批准验证' }).getByRole('heading').filter({ hasText: '已批准' }).waitFor();
    await page.setViewportSize({ width: 375, height: 812 });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Portal changes mobile overflow');
    await page.screenshot({ path: 'output/playwright/portal-real-changes-mobile.png', fullPage: true });
    panel = admin.getByRole('region', { name: '门户企业资料变更审核', exact: true });
    await panel.getByRole('button', { name: '资料变更审核', exact: true }).click();
    await panel.getByRole('row').filter({ hasText: '浏览器批准验证' }).getByRole('button', { name: '查看变更' }).click();
    await panel.getByRole('heading', { name: '变更前后对比 · 已批准', exact: true }).scrollIntoViewIfNeeded();
    await admin.screenshot({ path: 'output/playwright/portal-real-changes-review.png', fullPage: true });
    await admin.setViewportSize({ width: 375, height: 812 });
    await admin.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await panel.getByRole('heading', { name: '变更前后对比 · 已批准', exact: true }).scrollIntoViewIfNeeded();
    const bounds = await panel.boundingBox();
    if (!bounds || bounds.x < -1 || bounds.x + bounds.width > 376) throw new Error('Review panel extends outside the mobile viewport');
    if (await admin.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Review mobile page overflow');
    await admin.screenshot({ path: 'output/playwright/portal-real-changes-review-mobile.png', fullPage: true });
    await page.getByRole('button', { name: '退出当前会话', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '已退出当前会话' }).waitFor();
  } finally { await reader.close(); await admin.close(); }
}
